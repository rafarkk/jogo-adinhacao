// dentes ao longo de uma curva quadrática, apontando na direção `sentido` (1 = para baixo)
const dentesCurva = (x0, y0, qx, qy, x1, y1, n, sentido, tam = 9) => {
  let s = ''
  for (let i = 0; i <= n; i++) {
    const t = i / n
    const x = (1 - t) ** 2 * x0 + 2 * (1 - t) * t * qx + t * t * x1
    const y = (1 - t) ** 2 * y0 + 2 * (1 - t) * t * qy + t * t * y1
    s += p(`M${x - 4} ${y} L${x} ${y + tam * sentido} L${x + 4} ${y} Z`, '#fff')
  }
  return s
}

