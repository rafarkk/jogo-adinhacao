function minion(cx, topo, larg, alt, doisOlhos) {
  const x0 = cx - larg / 2
  const base = topo + alt
  const corpo = (f) => r(x0, topo, larg, alt, f, larg / 2)
  const oy = topo + alt * 0.3 + 4
  const olhoM = (x, raio) => c(x, oy, raio + 5, '#9AA5B4', borda(TINTA, 2)) + c(x, oy, raio, '#fff') + c(x + 1, oy + 1, raio * 0.5, '#8B5A2B') + c(x + 1, oy + 1, raio * 0.25, TINTA) + c(x + 3, oy - 2, 1.5, '#fff')
  return (
    e(cx - 9, base + 3, 9, 5, TINTA) + e(cx + 9, base + 3, 9, 5, TINTA) +
    l(`M${x0 + 2} ${topo + alt * 0.56} L${x0 - 12} ${topo + alt * 0.74}`, '#FFD93B', 7) + c(x0 - 13, topo + alt * 0.76, 6, TINTA) +
    l(`M${x0 + larg - 2} ${topo + alt * 0.56} L${x0 + larg + 12} ${topo + alt * 0.74}`, '#FFD93B', 7) + c(x0 + larg + 13, topo + alt * 0.76, 6, TINTA) +
    corpo('#FFD93B') +
    recorte(corpo('#000'),
      r(x0, base - alt * 0.3, larg, alt, '#3F7FE0') + r(cx - larg * 0.3, base - alt * 0.44, larg * 0.6, alt * 0.16, '#3F7FE0') +
      r(cx - 7, base - alt * 0.4, 14, 10, '#2F64B8', 3) + c(cx - larg * 0.3 + 4, base - alt * 0.42, 2.5, TINTA) + c(cx + larg * 0.3 - 4, base - alt * 0.42, 2.5, TINTA)) +
    r(x0, oy - 4, larg, 8, '#2B2B33') +
    (doisOlhos ? olhoM(cx - 11, 8) + olhoM(cx + 11, 8) : olhoM(cx, 11)) +
    l(`M${cx - 10} ${topo + alt * 0.52} Q${cx} ${topo + alt * 0.6} ${cx + 10} ${topo + alt * 0.52}`, TINTA, 2.5) +
    l(`M${cx} ${topo + 2} L${cx - 6} ${topo - 10} M${cx} ${topo + 2} L${cx + 5} ${topo - 11} M${cx} ${topo + 2} V${topo - 12}`, TINTA, 1.6)
  )
}

