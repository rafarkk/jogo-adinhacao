// anel (rosquinha) com furo de verdade, para o fundo da carta aparecer
const anel = (cx, cy, R, ri, cor) =>
  p(
    `M${cx - R} ${cy} a${R} ${R} 0 1 0 ${2 * R} 0 a${R} ${R} 0 1 0 ${-2 * R} 0 Z ` +
      `M${cx - ri} ${cy} a${ri} ${ri} 0 1 0 ${2 * ri} 0 a${ri} ${ri} 0 1 0 ${-2 * ri} 0 Z`,
    cor,
    'fill-rule="evenodd"',
  )

const xadrez = (cor, passo = 16, w = 2.5) => {
  let s = ''
  for (let k = -200; k <= 400; k += passo) s += l(`M${k} 0 L${k + 200} 200`, cor, w) + l(`M${k} 0 L${k - 200} 200`, cor, w)
  return s
}

